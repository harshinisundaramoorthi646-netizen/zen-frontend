import React, { useState } from 'react';
import { usePlatformStore } from '../../store/usePlatformStore';
import { DataTable, Column } from '../../components/common/DataTable';
import { StatusBadge } from '../../components/common/StatusBadge';
import { Lead } from '../../types';

export const AdminLeads: React.FC = () => {
  const { leads, members } = usePlatformStore();
  const [statusFilter, setStatusFilter] = useState('All');

  const filteredLeads = leads.filter((l) => {
    if (statusFilter !== 'All' && l.status !== statusFilter) return false;
    return true;
  });

  const columns: Column<Lead>[] = [
    {
      header: 'Lead ID',
      accessorKey: 'id',
      sortable: true,
      cell: (row) => <span className="font-bold text-brand-700">{row.id}</span>,
    },
    {
      header: 'Lead & Company',
      accessorKey: 'name',
      sortable: true,
      cell: (row) => (
        <div>
          <p className="font-bold text-slate-900">{row.name}</p>
          <p className="text-xs text-slate-500">{row.company}</p>
        </div>
      ),
    },
    {
      header: 'Contact',
      accessorKey: 'phone',
      cell: (row) => (
        <div className="text-xs">
          <p className="font-medium text-slate-800">{row.phone || '—'}</p>
          <p className="text-slate-500">{row.email || '—'}</p>
        </div>
      ),
    },
    {
      header: 'Area',
      accessorKey: 'area',
      sortable: true,
    },
    {
      header: 'Generated By',
      accessorKey: 'generatedByName',
      sortable: true,
    },
    {
      header: 'Date',
      accessorKey: 'date',
      sortable: true,
    },
    {
      header: 'Status',
      accessorKey: 'status',
      cell: (row) => <StatusBadge status={row.status} />,
    },
  ];

  return (
    <div className="space-y-6">
      <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4 border-b border-slate-200 pb-4">
        <div>
          <h1 className="text-xl font-bold text-slate-900">Admin Lead Master Register</h1>
          <p className="text-xs text-slate-500 mt-1">Complete view of all leads across Team A and Team B.</p>
        </div>
      </div>

      <div className="flex items-center gap-2 bg-white p-4 rounded-xl border border-slate-200 shadow-2xs">
        <label className="text-xs font-bold uppercase text-slate-600">Filter Status:</label>
        <select
          value={statusFilter}
          onChange={(e) => setStatusFilter(e.target.value)}
          className="rounded-lg border border-slate-300 bg-slate-50 text-xs font-semibold py-1.5 px-3 focus:outline-none"
        >
          <option value="All">All Leads ({leads.length})</option>
          <option value="New">New ({leads.filter((l) => l.status === 'New').length})</option>
          <option value="Forwarded to Team B">Forwarded ({leads.filter((l) => l.status === 'Forwarded to Team B').length})</option>
          <option value="Selected">Selected ({leads.filter((l) => l.status === 'Selected').length})</option>
          <option value="Waiting">Waiting ({leads.filter((l) => l.status === 'Waiting').length})</option>
          <option value="Rejected">Rejected ({leads.filter((l) => l.status === 'Rejected').length})</option>
        </select>
      </div>

      <DataTable data={filteredLeads} columns={columns} pageSize={10} searchPlaceholder="Search all leads..." />
    </div>
  );
};
