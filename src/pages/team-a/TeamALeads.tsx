import React, { useState } from 'react';
import { UserPlus, Send } from 'lucide-react';
import { usePlatformStore } from '../../store/usePlatformStore';
import { leadService } from '../../services';
import { DataTable, Column } from '../../components/common/DataTable';
import { StatusBadge } from '../../components/common/StatusBadge';
import { Button } from '../../components/ui/Button';
import { AddLeadModal } from '../../components/leads/AddLeadModal';
import { Lead } from '../../types';
import { toast } from 'sonner';

export const TeamALeads: React.FC = () => {
  const { leads, members } = usePlatformStore();
  const [isAddModalOpen, setIsAddModalOpen] = useState(false);
  const [statusFilter, setStatusFilter] = useState<string>('All');
  const [memberFilter, setMemberFilter] = useState<string>('All');

  const teamAMembers = members.filter((m) => m.team === 'Team A');

  const filteredLeads = leads.filter((lead) => {
    if (statusFilter !== 'All' && lead.status !== statusFilter) return false;
    if (memberFilter !== 'All' && lead.generatedByMemberId !== memberFilter) return false;
    return true;
  });

  const handleForward = async (leadId: string) => {
    try {
      await leadService.forwardLead(leadId);
      toast.success(`Lead ${leadId} forwarded to Team B!`);
    } catch {
      toast.error('Failed to forward lead.');
    }
  };

  const columns: Column<Lead>[] = [
    {
      header: 'Lead ID',
      accessorKey: 'id',
      sortable: true,
      cell: (row) => <span className="font-bold text-brand-700">{row.id}</span>,
    },
    {
      header: 'Lead Name & Company',
      accessorKey: 'name',
      sortable: true,
      cell: (row) => (
        <div>
          <p className="font-bold text-slate-900">{row.name}</p>
          <p className="text-xs text-slate-500">{row.company}</p>
        </div>
      ),
    },
    {
      header: 'Contact / Email',
      accessorKey: 'phone',
      cell: (row) => (
        <div className="text-xs">
          <p className="font-medium text-slate-800">{row.phone || '—'}</p>
          <p className="text-slate-500">{row.email || '—'}</p>
        </div>
      ),
    },
    {
      header: 'Area',
      accessorKey: 'area',
      sortable: true,
    },
    {
      header: 'Generated By',
      accessorKey: 'generatedByName',
      sortable: true,
      cell: (row) => (
        <span className="text-xs font-semibold bg-slate-100 text-slate-700 px-2 py-0.5 rounded">
          {row.generatedByName}
        </span>
      ),
    },
    {
      header: 'Date',
      accessorKey: 'date',
      sortable: true,
    },
    {
      header: 'Status',
      accessorKey: 'status',
      cell: (row) => <StatusBadge status={row.status} />,
    },
    {
      header: 'Actions',
      cell: (row) =>
        row.status === 'New' ? (
          <Button
            size="sm"
            variant="outline"
            onClick={() => handleForward(row.id)}
            className="text-brand-600 border-brand-200 hover:bg-brand-50"
          >
            <Send className="h-3.5 w-3.5 mr-1" />
            Forward to Team B
          </Button>
        ) : (
          <span className="text-xs text-slate-400 italic">In Team B Queue</span>
        ),
    },
  ];

  return (
    <div className="space-y-6">
      <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4 border-b border-slate-200 pb-4">
        <div>
          <h1 className="text-xl font-bold text-slate-900">Team A Lead Register</h1>
          <p className="text-xs text-slate-500 mt-1">
            Manage all captured leads and track status forwarding to Team B.
          </p>
        </div>
        <Button onClick={() => setIsAddModalOpen(true)}>
          <UserPlus className="h-4 w-4 mr-1.5" />
          + Add Lead
        </Button>
      </div>

      {/* Filter Controls */}
      <div className="flex flex-wrap items-center gap-4 bg-white p-4 rounded-xl border border-slate-200 shadow-2xs">
        <div className="flex items-center gap-2">
          <label className="text-xs font-bold uppercase text-slate-600">Status:</label>
          <select
            value={statusFilter}
            onChange={(e) => setStatusFilter(e.target.value)}
            className="rounded-lg border border-slate-300 bg-slate-50 text-xs font-semibold py-1.5 px-3 focus:outline-none focus:border-brand-500"
          >
            <option value="All">All Statuses ({leads.length})</option>
            <option value="New">New ({leads.filter((l) => l.status === 'New').length})</option>
            <option value="Forwarded to Team B">Forwarded ({leads.filter((l) => l.status === 'Forwarded to Team B').length})</option>
            <option value="Selected">Selected ({leads.filter((l) => l.status === 'Selected').length})</option>
            <option value="Waiting">Waiting ({leads.filter((l) => l.status === 'Waiting').length})</option>
            <option value="Rejected">Rejected ({leads.filter((l) => l.status === 'Rejected').length})</option>
          </select>
        </div>

        <div className="flex items-center gap-2">
          <label className="text-xs font-bold uppercase text-slate-600">Generated By:</label>
          <select
            value={memberFilter}
            onChange={(e) => setMemberFilter(e.target.value)}
            className="rounded-lg border border-slate-300 bg-slate-50 text-xs font-semibold py-1.5 px-3 focus:outline-none focus:border-brand-500"
          >
            <option value="All">All Team A Members</option>
            {teamAMembers.map((m) => (
              <option key={m.id} value={m.id}>
                {m.name}
              </option>
            ))}
          </select>
        </div>
      </div>

      <DataTable
        data={filteredLeads}
        columns={columns}
        pageSize={10}
        searchPlaceholder="Search leads by name, company, area, phone..."
        searchFields={['name', 'company', 'area', 'phone', 'email', 'generatedByName']}
      />

      <AddLeadModal isOpen={isAddModalOpen} onClose={() => setIsAddModalOpen(false)} />
    </div>
  );
};
