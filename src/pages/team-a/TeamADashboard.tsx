import React, { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { UserPlus, Send, CheckCircle2, Clock, Users, ArrowUpRight } from 'lucide-react';
import { usePlatformStore } from '../../store/usePlatformStore';
import { leadService } from '../../services';
import { StatCard } from '../../components/common/StatCard';
import { DataTable, Column } from '../../components/common/DataTable';
import { StatusBadge } from '../../components/common/StatusBadge';
import { Button } from '../../components/ui/Button';
import { AddLeadModal } from '../../components/leads/AddLeadModal';
import { Lead } from '../../types';
import { toast } from 'sonner';
import { BarChart, Bar, XAxis, YAxis, Tooltip, ResponsiveContainer, CartesianGrid } from 'recharts';

export const TeamADashboard: React.FC = () => {
  const { leads, currentUser, members } = usePlatformStore();
  const [isAddLeadOpen, setIsAddLeadOpen] = useState(false);
  const navigate = useNavigate();

  // Filter team A members
  const teamAMembers = members.filter((m) => m.team === 'Team A');

  // Stats calculation
  const totalLeads = leads.length;
  const myLeads = leads.filter((l) => l.generatedByMemberId === currentUser.id).length;
  const forwardedLeads = leads.filter((l) => l.status === 'Forwarded to Team B').length;
  const selectedLeads = leads.filter((l) => l.status === 'Selected').length;
  const waitingLeads = leads.filter((l) => l.status === 'Waiting').length;

  // Performance data per member
  const performanceData = teamAMembers.map((member) => {
    const memberLeads = leads.filter((l) => l.generatedByMemberId === member.id);
    return {
      name: member.name,
      total: memberLeads.length,
      forwarded: memberLeads.filter((l) => l.status !== 'New').length,
      selected: memberLeads.filter((l) => l.status === 'Selected').length,
    };
  });

  const handleForward = async (leadId: string) => {
    try {
      await leadService.forwardLead(leadId);
      toast.success(`Lead ${leadId} forwarded to Team B!`, {
        description: 'Team B can now view, call, and schedule follow-ups for this lead.',
      });
    } catch {
      toast.error('Failed to forward lead.');
    }
  };

  const columns: Column<Lead>[] = [
    {
      header: 'Lead ID',
      accessorKey: 'id',
      sortable: true,
      cell: (row) => <span className="font-bold text-brand-700">{row.id}</span>,
    },
    {
      header: 'Lead Name & Company',
      accessorKey: 'name',
      sortable: true,
      cell: (row) => (
        <div>
          <p className="font-bold text-slate-900">{row.name}</p>
          <p className="text-xs text-slate-500">{row.company}</p>
        </div>
      ),
    },
    {
      header: 'Contact / Email',
      accessorKey: 'phone',
      cell: (row) => (
        <div className="text-xs">
          <p className="font-medium text-slate-800">{row.phone || '—'}</p>
          <p className="text-slate-500">{row.email || '—'}</p>
        </div>
      ),
    },
    {
      header: 'Area',
      accessorKey: 'area',
      sortable: true,
      cell: (row) => <span className="text-xs font-medium text-slate-700">{row.area}</span>,
    },
    {
      header: 'Generated By',
      accessorKey: 'generatedByName',
      sortable: true,
      cell: (row) => (
        <span className="text-xs font-semibold bg-slate-100 text-slate-700 px-2 py-0.5 rounded">
          {row.generatedByName}
        </span>
      ),
    },
    {
      header: 'Date',
      accessorKey: 'date',
      sortable: true,
    },
    {
      header: 'Status',
      accessorKey: 'status',
      cell: (row) => <StatusBadge status={row.status} />,
    },
    {
      header: 'Action',
      cell: (row) =>
        row.status === 'New' ? (
          <Button
            size="sm"
            variant="outline"
            onClick={() => handleForward(row.id)}
            className="text-brand-600 border-brand-200 hover:bg-brand-50"
          >
            <Send className="h-3.5 w-3.5 mr-1" />
            Forward to Team B
          </Button>
        ) : (
          <span className="text-xs text-slate-400 italic">In Team B Workflow</span>
        ),
    },
  ];

  return (
    <div className="space-y-6">
      {/* Top Banner Header */}
      <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4 bg-gradient-to-r from-brand-900 via-brand-800 to-indigo-900 p-6 rounded-2xl text-white shadow-lg">
        <div>
          <span className="inline-block px-2.5 py-0.5 rounded-full bg-brand-500/30 text-brand-200 text-xs font-bold uppercase tracking-wider mb-2">
            Team A Workstation
          </span>
          <h1 className="text-2xl font-extrabold tracking-tight">Lead Generation Hub</h1>
          <p className="text-xs text-brand-200 mt-1">
            Capture prospective leads, manage outreach pipeline, and forward qualified leads to Team B.
          </p>
        </div>
        <Button
          size="lg"
          variant="primary"
          onClick={() => setIsAddLeadOpen(true)}
          className="bg-white text-brand-900 hover:bg-brand-50 shadow-md font-bold shrink-0"
        >
          <UserPlus className="h-5 w-5 mr-1 text-brand-700" />
          + Add Lead
        </Button>
      </div>

      {/* Summary Cards */}
      <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-5 gap-4">
        <StatCard
          title="My Generated Leads"
          value={myLeads}
          subtext={`Logged by ${currentUser.name}`}
          icon={<Users className="h-5 w-5" />}
          variant="brand"
        />
        <StatCard
          title="Total Leads"
          value={totalLeads}
          subtext="Platform total"
          icon={<Users className="h-5 w-5" />}
          variant="blue"
        />
        <StatCard
          title="Leads Forwarded"
          value={forwardedLeads}
          subtext="Sent to Team B"
          icon={<Send className="h-5 w-5" />}
          variant="purple"
        />
        <StatCard
          title="Leads Selected"
          value={selectedLeads}
          subtext="Converted clients"
          icon={<CheckCircle2 className="h-5 w-5" />}
          variant="emerald"
        />
        <StatCard
          title="Leads Waiting"
          value={waitingLeads}
          subtext="In review"
          icon={<Clock className="h-5 w-5" />}
          variant="amber"
        />
      </div>

      {/* Team Performance & Recent Leads Table */}
      <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
        {/* Performance Chart & Table */}
        <div className="lg:col-span-1 bg-white border border-slate-200 rounded-xl p-5 shadow-sm space-y-4">
          <div className="flex items-center justify-between border-b border-slate-100 pb-3">
            <h3 className="text-sm font-bold text-slate-900">Team A Member Performance</h3>
            <span className="text-xs font-semibold text-brand-600 bg-brand-50 px-2 py-0.5 rounded">
              {teamAMembers.length} Members
            </span>
          </div>

          <div className="h-48 w-full">
            <ResponsiveContainer width="100%" height="100%">
              <BarChart data={performanceData}>
                <CartesianGrid strokeDasharray="3 3" vertical={false} stroke="#f1f5f9" />
                <XAxis dataKey="name" tick={{ fontSize: 10 }} />
                <YAxis tick={{ fontSize: 10 }} />
                <Tooltip
                  contentStyle={{ backgroundColor: '#0f172a', borderRadius: '8px', color: '#fff', fontSize: '12px' }}
                />
                <Bar dataKey="total" fill="#0074ca" radius={[4, 4, 0, 0]} name="Total Leads" />
                <Bar dataKey="selected" fill="#10b981" radius={[4, 4, 0, 0]} name="Selected" />
              </BarChart>
            </ResponsiveContainer>
          </div>

          <div className="space-y-2">
            {performanceData.map((m, idx) => (
              <div key={idx} className="flex items-center justify-between text-xs p-2 rounded-lg bg-slate-50 border border-slate-100">
                <span className="font-bold text-slate-800">{m.name}</span>
                <div className="flex items-center gap-3">
                  <span className="text-slate-500">{m.total} Generated</span>
                  <span className="font-bold text-emerald-600">{m.selected} Selected</span>
                </div>
              </div>
            ))}
          </div>
        </div>

        {/* Lead Register Table */}
        <div className="lg:col-span-2 bg-white border border-slate-200 rounded-xl p-5 shadow-sm space-y-4">
          <div className="flex items-center justify-between">
            <h3 className="text-sm font-bold text-slate-900">All Generated Leads</h3>
            <Button
              variant="ghost"
              size="sm"
              onClick={() => navigate('/team-a/leads')}
              className="text-xs text-brand-600"
            >
              View All Leads <ArrowUpRight className="h-3.5 w-3.5 ml-1" />
            </Button>
          </div>

          <DataTable
            data={leads}
            columns={columns}
            pageSize={6}
            searchPlaceholder="Search leads by name, company, area..."
            searchFields={['name', 'company', 'area', 'phone', 'email', 'generatedByName']}
          />
        </div>
      </div>

      <AddLeadModal
        isOpen={isAddLeadOpen}
        onClose={() => setIsAddLeadOpen(false)}
      />
    </div>
  );
};
